def header(title: str, task: str) -> list[str]:
    """Standard transcript header, marking the output as really captured."""
    return [
        f"# {title}",
        "",
        f"**{task}**",
        "",
        "Captured output. Generated by `python -m scripts.generate_demonstrations`",
        f"at {datetime.now(timezone.utc).isoformat(timespec='seconds')}.",
        "",
        "| Setting | Value |",
        "| --- | --- |",
        f"| `MOCK_LLM` | `{SETTINGS.mock_llm}` |",
        f"| `CREW_MODE` | `{SETTINGS.crew_mode}` |",
        f"| `EMBEDDING_BACKEND` | `{SETTINGS.embedding_backend}` |",
        f"| Retrieval collection | `{SETTINGS.recommended_collection_name}` |",
        f"| `TOP_K` | `{SETTINGS.top_k}` |",
        f"| `REVIEW_ENABLED` | `{SETTINGS.review_enabled}` |",
        "",
    ]


def write(name: str, lines: list[str]) -> Path:
    TRANSCRIPTS_DIR.mkdir(parents=True, exist_ok=True)
    path = TRANSCRIPTS_DIR / name
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"[demo] wrote {path}")
    return path


def response_block(response: SupportResponse) -> list[str]:
    """Render the interesting fields of a validated response."""
    return [
        "```json",
        json.dumps(
            {
                "trace_id": response.trace_id,
                "response_type": response.response_type,
                "answer": response.answer,
                "sources": response.sources,
                "grounded": response.grounded,
                "top_similarity": round(response.top_similarity, 4),
                "threshold": round(response.threshold, 4),
                "tools_invoked": response.tools_invoked,
                "guardrails_fired": response.guardrails_fired,
                "pii_masked": response.pii_masked,
                "cache_hit": response.cache_hit,
                "escalation_recommended": response.escalation_recommended,
                "review_approved": response.review_approved,
                "review_revised": response.review_revised,
                "review_reason": response.review_reason,
                "query_as_seen_by_the_agent": response.query,
            },
            indent=2,
            ensure_ascii=False,
        ),
        "```",
        "",
    ]


def make_context(query: str, *, trace_id: str, inject: bool = False) -> CrewRunContext:
    record_id = extract_record_id(query)
    return CrewRunContext(
        trace_id=trace_id,
        session_id=f"demo::{trace_id}",
        query=query,
        route=classify_route(query),
        record_id=record_id,
        inject_unsupported_claim=inject,
    )


