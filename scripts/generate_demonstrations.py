DEMOS: dict[str, str] = {
    "rag": "Task 4 grounded generation",
    "tools": "Task 7 tool invocation",
    "memory": "Task 8 session memory",
    "guardrails": "Task 10 guardrails",
    "review": "Task 14 Autogen review",
    "budget": "Task 15 budget cap",
    "autonomy": "Task 15 least autonomy",
    "cache": "Task 16 response cache",
    "escalation": "Task 6 escalation score",
}


async def _run_all(selected: list[str]) -> None:
    service = SupportService(SETTINGS)
    generator = service.generator


    synchronous: dict[str, Callable[[], None]] = {
        "rag": lambda: demo_rag(generator),
        "tools": lambda: demo_tool_invocation(generator),
        "autonomy": demo_least_autonomy,
        "cache": lambda: demo_cache(generator),
        "escalation": demo_escalation,
    }


    for name in selected:
        print(f"[demo] running {name}: {DEMOS[name]}")
        if name in synchronous:
            synchronous[name]()
        elif name == "memory":
            await demo_memory(service)
        elif name == "guardrails":
            await demo_guardrails(service)
        elif name == "review":
            await demo_review(generator)
        elif name == "budget":
            await demo_budget(service)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--only",
        nargs="+",
        choices=sorted(DEMOS),
        default=None,
        help="run only the named demonstrations",
    )
    args = parser.parse_args(argv)


    configure_logging(SETTINGS)
    ensure_runtime_directories(SETTINGS)


    # Deterministic order regardless of the order the flags were typed in.
    selected = [name for name in DEMOS if args.only is None or name in args.only]


    try:
        asyncio.run(_run_all(selected))
    except Exception as exc:  # noqa: BLE001 - reported with the failing demo
        print(f"\n[demo] FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2


    print(f"\n[demo] regenerated {len(selected)} transcript group(s) in {TRANSCRIPTS_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())


