"""Task 13 - run the 15-query evaluation and report all four scores.


    python -m evaluation.run_evaluation


Writes ``reports/evaluation_report.md`` and prints the same table. Every query
gets a fresh ``session_id`` so session memory cannot leak context between
independent test cases.
"""


from __future__ import annotations


import argparse
import asyncio
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


from app.config import REPORTS_DIR, SETTINGS, Settings, ensure_runtime_directories
from app.logging_config import configure_logging
from app.models import SupportResponse
from app.services.support_service import SupportService
from agents.governance import BudgetExceededError
from evaluation.mock_judge import (
    EvalCase,
    JudgeScore,
    averages,
    judge,
    load_test_set,
    render_judge_prompt,
)




async def _evaluate(
    service: SupportService, cases: list[EvalCase]
) -> list[tuple[EvalCase, SupportResponse, JudgeScore]]:
    results: list[tuple[EvalCase, SupportResponse, JudgeScore]] = []
    for case in cases:
        try:
            response = await service.answer(
                case.query,
                # A fresh session per case: no cross-case memory contamination.
                session_id=f"eval::{case.id}",
                endpoint="evaluation",
                transport="script",
            )
        except BudgetExceededError as exc:
            raise RuntimeError(
                f"evaluation case {case.id} was rejected by the runtime budget cap "
                f"({exc.decision.message}). Raise MAX_REQUEST_CHARACTERS or shorten "
                "the query - a graded evaluation query must not be budget-rejected."
            ) from exc
        results.append((case, response, judge(case, response)))
    return results




def format_report(
    results: list[tuple[EvalCase, SupportResponse, JudgeScore]],
    means: dict[str, float],
    settings: Settings,
) -> str:
    """Render the Task 13 evaluation report."""
    lines = [
        "# Task 13 - Evaluation report (15 queries, four properties)",
        "",
        "Generated by `python -m evaluation.run_evaluation`. Every score below is",
        "produced by the deterministic rule-based judge in `evaluation/mock_judge.py`",
        "running under `MOCK_LLM`; none of it is a random draw, and the same response",
        "always scores the same.",
        "",
        f"- **Run at:** {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"- **MOCK_LLM:** {settings.mock_llm}",
        f"- **Crew mode:** `{settings.crew_mode}`",
        f"- **Embedding backend:** `{settings.embedding_backend}`",
        f"- **Retrieval collection:** `{settings.recommended_collection_name}`",
        f"- **Queries:** {len(results)}",
        "",
        "The judge is rule-based rather than an independent semantic model. It scores",
        "against the declared expectations in `evaluation/test_set.json` plus",
        "observable response properties, so it cannot recognise a paraphrase and",
        "cannot spot a plausible answer that is wrong in a way the expectations do not",
        "cover. That limitation is the price of reproducibility.",
        "",
        "## Per-query scores",
        "",
        "| Query id | Accuracy | Grounding | Completeness | Safety | Mean |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    lines.extend(
        f"| `{score.case_id}` | {score.accuracy:.2f} | {score.grounding:.2f} "
        f"| {score.completeness:.2f} | {score.safety:.2f} | {score.mean:.2f} |"
        for _, _, score in results
    )


    lines += [
        "",
        "## Averages across all 15 queries",
        "",
        "| Property | Average |",
        "| --- | --- |",
        f"| Accuracy | **{means['accuracy']:.4f}** |",
        f"| Grounding | **{means['grounding']:.4f}** |",
        f"| Completeness | **{means['completeness']:.4f}** |",
        f"| Safety | **{means['safety']:.4f}** |",
        f"| Overall mean | **{means['overall']:.4f}** |",
        "",
        "## Per-query detail",
        "",
    ]


    for case, response, score in results:
        lines += [
            f"### `{case.id}`",
            "",
            f"> {case.query}",
            "",
            f"- expectation: response_type `{case.expected_response_type}`, "
            f"topic `{case.expected_topic or 'n/a'}`, grounded "
            f"`{case.expect_grounded}`, safety profile `{case.safety_profile}`",
            f"- observed: response_type `{response.response_type}`, grounded "
            f"`{response.grounded}`, sources `{response.sources or 'none'}`, "
            f"top similarity `{response.top_similarity:.4f}`, threshold "
            f"`{response.threshold:.4f}`",
            f"- tools invoked: `{response.tools_invoked or 'none'}`",
            f"- guardrails fired: `{response.guardrails_fired or 'none'}`",
            f"- review: approved `{response.review_approved}`, revised "
            f"`{response.review_revised}`",
            f"- answer: {response.answer}",
            "",
            f"- **Accuracy {score.accuracy:.2f}** - {score.reasons['accuracy']}",
            f"- **Grounding {score.grounding:.2f}** - {score.reasons['grounding']}",
            f"- **Completeness {score.completeness:.2f}** - "
            f"{score.reasons['completeness']}",
            f"- **Safety {score.safety:.2f}** - {score.reasons['safety']}",
            "",
            "<details><summary>LLM-as-judge prompt as rendered for this query</summary>",
            "",
            "```text",
            render_judge_prompt(case, response),
            "```",
            "",
            "</details>",
            "",
        ]


    imperfect = [
        (score.case_id, score.failures) for _, _, score in results if score.failures
    ]
    lines += ["## Queries that did not score full marks", ""]
    if not imperfect:
        lines.append("None: every query scored 1.00 on all four properties.")
    else:
        for case_id, failures in imperfect:
            lines.append(f"- `{case_id}`: " + "; ".join(failures))
    lines.append("")


    lines += [
        "## Topic coverage",
        "",
        "Queries q01-q12 cover one required knowledge-base topic each; q13 is an",
        "appointment-lookup edge case; q14 is deliberately out of scope; q15 is a",
        "prompt-injection edge case. That is 15 queries with all twelve required",
        "topics touched and three edge or out-of-scope cases.",
        "",
    ]
    return "\n".join(lines)




def write_report(text: str, *, path: Path | None = None) -> Path:
    target = path or (REPORTS_DIR / "evaluation_report.md")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return target




def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--json",
        dest="json_path",
        type=Path,
        default=None,
        help="also write the raw scores as JSON to this path",
    )
    args = parser.parse_args(argv)


    configure_logging(SETTINGS)
    ensure_runtime_directories(SETTINGS)


    cases = load_test_set()
    service = SupportService(SETTINGS)
    results = asyncio.run(_evaluate(service, cases))
    means = averages([score for _, _, score in results])


    report = format_report(results, means, SETTINGS)
    print(report)
    path = write_report(report)
    print(f"[evaluation] report written to {path}")


    if args.json_path:
        payload: dict[str, Any] = {
            "run_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "averages": means,
            "scores": [score.as_dict() for _, _, score in results],
            "responses": [response.model_dump() for _, response, _ in results],
        }
        args.json_path.parent.mkdir(parents=True, exist_ok=True)
        args.json_path.write_text(
            json.dumps(payload, indent=2, default=str) + "\n", encoding="utf-8"
        )
        print(f"[evaluation] raw scores written to {args.json_path}")


    return 0




if __name__ == "__main__":
    sys.exit(main())





